// French if the browser is in French, English in all other cases.

export const LANG_KEY = "EnergIA.lang";
export const LANGS = ["fr", "en"];

function stored() {
  try {
    return globalThis.localStorage?.getItem(LANG_KEY) ?? null;
  } catch {
    return null;
  }
}

export function pickLang(saved, browser) {
  if (LANGS.includes(saved)) return saved;
  return String(browser || "").toLowerCase().startsWith("fr") ? "fr" : "en";
}

